import { VERSION } from '../../version';
import { UmamiEvent, UmamiPropertyValue } from './types';

/** track() 进来的 Rudder 载荷，只声明映射需要读的字段（宽松取值，避免与上游大 union 耦合） */
type UmamiMappingPayload = {
    event: string;
    userId?: string;
    anonymousId?: string;
    properties?: Record<string, unknown> | undefined;
};

export type UmamiMappingContext = {
    client: string;
    path: string;
    userUuid?: string;
    /** 缺省由 LightdashConfig.umami.environment 提供 */
    environment: string;
};

/** 后端事件白名单：严格只发这些（Rudder 事件名 → Umami 事件名） */
const UMAMI_EVENT_MAP: Record<string, string> = {
    'dashboard.view': 'dashboard_view',
    'saved_chart.view': 'chart_view',
    'sql_chart.view': 'sql_chart_view',
    'query.executed': 'query_executed',
    'query.error': 'query_error',
    'download_results.started': 'download_started',
    'download_results.completed': 'download_completed',
    mcp_tool_call: 'mcp_tool_call',
    'user.logged_in': 'user_logged_in',
    'permission.updated': 'permission_updated',
    'project.deleted': 'project_deleted',
    'organization.deleted': 'organization_deleted',
    'user.deleted': 'user_deleted',
    'personal_access_token.created': 'pat_created',
    'share_url.created': 'share_link_created',
    'dbt_cloud_integration.deleted': 'dbt_cloud_integration_deleted',
};

/** 属性白名单：Rudder 属性键 → Umami 属性键（不在表内的一律不发） */
const UMAMI_PROPERTY_MAP: Record<string, string> = {
    organizationId: 'org_id',
    projectId: 'project_id',
    dashboardId: 'dashboard_id',
    savedChartId: 'chart_id',
    chartId: 'chart_id',
    fileType: 'file_type',
    numRows: 'num_rows',
    toolName: 'tool_name',
    authType: 'auth_type',
    durationMs: 'duration_ms',
    success: 'success',
    // query.executed 的上游属性名是 context；queryContext 兼容 P3 重命名
    context: 'query_context',
    queryContext: 'query_context',
    metricsCount: 'metrics_count',
    dimensionsCount: 'dimensions_count',
    parametersCount: 'parameters_count',
    loginProvider: 'login_provider',
    autoGenerated: 'auto_generated',
    method: 'method',
    newUser: 'new_user',
    generatedInvite: 'generated_invite',
    mcpClient: 'mcp_client',
    // 看板/图表查看事件的扩展字段（由 P3 增加，按可选读取）
    dashboardSlug: 'dashboard_slug',
    dashboardName: 'dashboard_name',
    spaceUuid: 'space_id',
    spaceName: 'space_name',
    chartSlug: 'chart_slug',
    chartName: 'chart_name',
    chartKind: 'chart_kind',
};

const isUmamiPropertyValue = (value: unknown): value is UmamiPropertyValue =>
    typeof value === 'string' ||
    typeof value === 'number' ||
    typeof value === 'boolean';

/**
 * 白名单事件 → UmamiEvent；非白名单事件返回 null（严格不发）。
 * distinct_id 解析链：
 * payload.userId ?? payload.properties.userId ?? payload.properties.createdUserId
 *   ?? ctx.userUuid ?? 'server'
 */
export const mapLightdashEvent = (
    payload: UmamiMappingPayload,
    ctx: UmamiMappingContext,
): UmamiEvent | null => {
    const umamiEventName = UMAMI_EVENT_MAP[payload.event];
    if (umamiEventName === undefined) {
        return null;
    }

    const properties = payload.properties ?? {};
    const umamiProperties: Record<string, UmamiPropertyValue> = {};

    // 只挑白名单键；非标量（数组/对象/undefined/null）丢弃
    for (const [key, value] of Object.entries(properties)) {
        const umamiKey = UMAMI_PROPERTY_MAP[key];
        if (umamiKey !== undefined && isUmamiPropertyValue(value)) {
            umamiProperties[umamiKey] = value;
        }
    }

    // 公共属性
    umamiProperties.client = ctx.client || 'unknown';
    umamiProperties.app_version = VERSION;
    umamiProperties.env = ctx.environment;

    // distinct_id 解析链
    const distinctId =
        payload.userId ??
        (typeof properties.userId === 'string'
            ? properties.userId
            : undefined) ??
        (typeof properties.createdUserId === 'string'
            ? properties.createdUserId
            : undefined) ??
        ctx.userUuid ??
        'server';

    return {
        event: umamiEventName,
        distinctId,
        ...(payload.anonymousId !== undefined
            ? { anonymousId: payload.anonymousId }
            : {}),
        time: Date.now(),
        properties: umamiProperties,
    };
};
